/// A headless grid: rows of cells, navigated in two dimensions with the arrow keys.
///
/// The rows and cells come from `collection` (built with `CollectionBuilder::row`): render one
/// [`GridRow`] per row and one [`GridCell`] per cell, in collection order.
///
/// Default class: `leptonic-Grid`.
#[component]
#[allow(clippy::implicit_hasher)]
pub fn Grid(
    /// The rows and their cells.
    #[prop(into)]
    collection: CollectionMemo,
    /// The grid's id (its rows' and cells' ids derive from it). Generated by default.
    #[prop(into, optional)]
    id: Option<crate::Id>,
    /// Whether arrow keys focus rows (and then cells) or only cells.
    #[prop(optional)]
    focus_mode: GridFocusMode,
    #[prop(into, optional)] selection_mode: Signal<SelectionMode>,
    #[prop(into, optional)] selection_behavior: Signal<SelectionBehavior>,
    /// The initially selected rows.
    #[prop(into, optional)]
    default_selection: Selection,
    /// The selection (controlled), replacing `default_selection`: a value or any signal.
    #[prop(into, optional)]
    selection: Option<Signal<Selection>>,
    /// Receives the new state: an `RwSignal`, `WriteSignal`, closure, `Callback`, ...
    #[prop(into, optional)]
    set_selection: Option<Out<Selection>>,
    #[prop(into, optional)] on_selection_change: Option<Callback<Selection>>,
    #[prop(into, optional)] disabled_keys: Option<Signal<HashSet<Key>>>,
    #[prop(optional)] disabled_behavior: DisabledBehavior,
    #[prop(into, optional)] disallow_empty_selection: Signal<bool>,
    #[prop(optional)] escape_key_behavior: EscapeKeyBehavior,
    /// Arrow keys wrap around at the ends.
    #[prop(optional)]
    should_focus_wrap: bool,
    #[prop(optional)] keyboard_navigation_behavior: KeyboardNavigationBehavior,
    /// Select rows when a press ends instead of when it starts (e.g. for draggable rows).
    #[prop(optional)]
    should_select_on_press_up: bool,
    /// Called with the key of an activated row.
    #[prop(into, optional)]
    on_row_action: Option<Callback<Key>>,
    /// Called with the key of an activated cell.
    #[prop(into, optional)]
    on_cell_action: Option<Callback<Key>>,
    #[prop(into, optional)] aria_label: MaybeProp<String>,
    /// Ids of elements labelling it.
    #[prop(into, optional)]
    aria_labelledby: MaybeProp<String>,
    #[prop(into, optional)] classes: Classes,
    #[prop(into, optional)] styles: Styles,
    children: Children,
) -> impl IntoView {
    crate::metrics::subject!();
    let classes = with_default_class("leptonic-Grid", classes);
    let (selection, on_selection_change) =
        ValueBinding::from_state_props(selection, set_selection, on_selection_change);
    let state = use_grid_state(UseGridStateInput {
        collection,
        selection: SelectionOptions {
            selection_mode,
            selection_behavior,
            default_selection,
            selection,
            on_selection_change,
            disallow_empty_selection,
            disabled_keys: disabled_keys.unwrap_or_default(),
            disabled_behavior,
            ..SelectionOptions::default()
        },
        focus_mode,
    });

    let UseGridReturn { grid: props, data } = use_grid(UseGridInput {
        aria_label,
        aria_labelledby: crate::utils::id::id_ref_prop(aria_labelledby),
        options: CollectionOptions {
            should_focus_wrap,
            escape_key_behavior,
            ..CollectionOptions::default()
        },
        keyboard_navigation_behavior,
        on_row_action,
        on_cell_action,
        state,
        element: CapturedElement::new(),
        id,
        keyboard_delegate: None,
        should_select_on_press_up,
    });

    view! {
        <Provider value=data>
            <div {..props.attrs()} class=classes style=styles>
                {children()}
            </div>
        </Provider>
    }
}

/// A group of rows of a [`Grid`] (`role="rowgroup"`).
///
/// Default class: `leptonic-GridRowGroup`.
#[component]
pub fn GridRowGroup(
    #[prop(into, optional)] classes: Classes,
    #[prop(into, optional)] styles: Styles,
    children: Children,
) -> impl IntoView {
    crate::metrics::subject!();
    let classes = with_default_class("leptonic-GridRowGroup", classes);
    let row_group = use_grid_row_group();
    view! {
        <div {..row_group.row_group.attrs()} class=classes style=styles>
            {children()}
        </div>
    }
}

/// A row of a [`Grid`], for the collection row `key`.
///
/// Data attributes: `data-selected`, `data-focused`, `data-focus-visible`, `data-disabled`,
/// `data-pressed`, `data-hovered` (rows that can be selected or have an action).
///
/// Default class: `leptonic-GridRow`.
#[component]
pub fn GridRow(
    /// The row's key in the grid's collection.
    #[prop(into)]
    key: Key,
    #[prop(into, optional)] classes: Classes,
    #[prop(into, optional)] styles: Styles,
    children: Children,
) -> impl IntoView {
    crate::metrics::subject!();
    let classes = with_default_class("leptonic-GridRow", classes);
    let Some(grid) = use_context::<GridData>() else {
        crate::utils::dev_warn!("a <GridRow> belongs in a <Grid>");
        return None;
    };
    // The row's resets and its hover's react to the disabled state in one effect.
    let (row, hover) = sharing_one_effect(|| {
        let row = use_grid_row(UseGridRowInput {
            grid,
            key,
            on_context_menu: None,
        });
        let (allows_selection, has_action) = (row.allows_selection, row.has_action);
        // Interactive rows show hover (react-aria-components' `Row`).
        let hover = use_hover(UseHoverInput {
            is_disabled: Signal::derive(move || !allows_selection.get() && !has_action.get()),
            on_hover_start: None,
            on_hover_end: None,
            on_hover_change: None,
        });
        (row, hover)
    });
    let UseGridRowReturn {
        row: row_props,
        is_selected,
        is_focused,
        is_disabled,
        is_pressed,
        ..
    } = row;
    let (attrs, row_styles) = row_props.attrs();
    let styles = row_styles.merge(styles);
    // Focused by keyboard (react-aria-components: the row's `useFocusRing`).
    let is_focus_visible = Signal::derive(move || is_focused.get() && is_focus_visible());

    Some(view! {
        <div
            {..attrs}
            {..hover.target.attrs()}
            class=classes
            style={styles}
            {..data_flags([
                ("data-focused", is_focused),
                ("data-focus-visible", is_focus_visible),
                ("data-pressed", is_pressed),
            ])}
            {..data_flags([
                ("data-hovered", hover.is_hovered),
                ("data-selected", is_selected),
                ("data-disabled", is_disabled),
            ])}
        >
            {children()}
        </div>
    })
}

/// A cell of a [`Grid`], for the collection cell `key` (`Key::cell(row, column)`).
///
/// Data attributes: `data-pressed`, `data-focused`, `data-focus-visible`.
///
/// Default class: `leptonic-GridCell`.
#[component]
pub fn GridCell(
    /// The cell's key in the grid's collection.
    #[prop(into)]
    key: Key,
    /// What gets focus: the cell, or its first focusable child. Defaults to the cell with
    /// `KeyboardNavigationBehavior::Tab` and the child otherwise.
    #[prop(optional)]
    focus_mode: Option<CellFocusMode>,
    /// Let ArrowLeft/ArrowRight move between the cell's children (and ArrowUp/ArrowDown between
    /// rows) even with `KeyboardNavigationBehavior::Tab`.
    #[prop(optional)]
    allows_arrow_navigation: bool,
    #[prop(into, optional)] classes: Classes,
    #[prop(into, optional)] styles: Styles,
    children: Children,
) -> impl IntoView {
    crate::metrics::subject!();
    let classes = with_default_class("leptonic-GridCell", classes);
    let Some(grid) = use_context::<GridData>() else {
        crate::utils::dev_warn!("a <GridCell> belongs in a <Grid>");
        return None;
    };
    let UseGridCellReturn {
        cell: grid_cell_props,
        is_pressed,
    } = use_grid_cell(UseGridCellInput {
        focus_mode,
        should_select_on_press_up: grid.should_select_on_press_up,
        grid,
        key,
        id: None,
        allows_arrow_navigation,
    });

    let (attrs, cell_styles) = grid_cell_props.attrs();
    let styles = cell_styles.merge(styles);
    // Focus on the cell itself (react-aria-components: the cell's `useFocusRing`).
    let UseFocusRingReturn {
        target: focus_ring,
        is_focused,
        ..
    } = use_focus_ring(UseFocusRingInput::default());

    Some(view! {
        <div
            {..attrs}
            {..focus_ring.attrs()}
            class=classes
            style={styles}
            {..data_flags([
                ("data-pressed", is_pressed),
                ("data-focused", is_focused),
            ])}
        >
            {children()}
        </div>
    })
}
